const dicts: Record<Lang, Dict> = { id, en };

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const Ctx = createContext<LangCtx>({
  lang: "id",
  setLang: () => {},
  t: (k) => k,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("id");

  useEffect(() => {
    const saved = localStorage.getItem("sapalive-lang");
    if (saved === "id" || saved === "en") setLangState(saved);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("sapalive-lang", l);
    document.documentElement.lang = l;
  }, []);

  const t = useCallback(
    (key: string) => dicts[lang][key] ?? id[key] ?? key,
    [lang]
  );

  return (
    <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
  );
}

export function useLang() {
  return useContext(Ctx);
}
